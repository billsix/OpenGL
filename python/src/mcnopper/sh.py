"""Real spherical-harmonics rotations (GLUS ``glus_sh.c``).

Generated by ``tools/mcnopper/transliterate_glus_sh.py``
from the C text and proven against a standalone build of the C on random
rotations -- do not edit by hand; re-run the script.

The three builders produce the band-1 (3x3), band-2 (5x5) and band-3 (7x7)
Wigner-D matrices for the *standard* real-SH basis, each band derived from
the lower ones (Ivanic & Ruedenberg recurrence as GLUS spells it out).
Storage is column-major flat arrays, indexed ``m[c * n + r]`` exactly as the
C's ``S1``/``S2``/``S3`` macros (``s1``/``s2``/``s3`` here).
"""

from __future__ import annotations

import numpy as np


def s1(m: np.ndarray, r: int, c: int) -> float:
    """= the C's S1(m, r, c): element (r, c) of a column-major 3x3."""
    return float(m[c * 3 + r])


def s2(m: np.ndarray, r: int, c: int) -> float:
    """= S2: element (r, c) of a column-major 5x5."""
    return float(m[c * 5 + r])


def s3(m: np.ndarray, r: int, c: int) -> float:
    """= S3: element (r, c) of a column-major 7x7."""
    return float(m[c * 7 + r])


def i1(r: int, c: int) -> int:
    return c * 3 + r


def i2(r: int, c: int) -> int:
    return c * 5 + r


def i3(r: int, c: int) -> int:
    return c * 7 + r


